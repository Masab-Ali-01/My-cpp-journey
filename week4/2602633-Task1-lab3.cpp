#include<iostream>
using namespace std;
int main(){
    int n1,n2;
    cout<<"Enter num 1 :";
    cin>>n1;
    cout<<"Enter num 2 :";
    cin>>n2;

    cout<<"\nAddition : "<<n1<<" + "<<n2<<" = "<<n1+n2;
    cout<<"\nSubtraction : "<<n1<<" - "<<n2<<" = "<<n1-n2;
    cout<<"\nMUltiplication : "<<n1<<" * "<<n2<<" = "<<n1*n2;
    cout<<"\nDivision : "<<n1<<" / "<<n2<<" = "<<n1/n2;
    cout<<"\nModulous :"<<n1<<" % "<<n2<<" = "<<n1%n2;
    return 0;
}